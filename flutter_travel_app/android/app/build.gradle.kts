// Google Maps API key: read from android/secrets.properties (gitignored,
// see secrets.properties.example) with an environment variable fallback for
// CI, so the key is never hardcoded in AndroidManifest.xml.
val secretsProperties = Properties()
val secretsPropertiesFile = rootProject.file("secrets.properties")
if (secretsPropertiesFile.exists()) {
    secretsProperties.load(FileInputStream(secretsPropertiesFile))
}
val googleMapsApiKey: String =
    secretsProperties.getProperty("GOOGLE_MAPS_API_KEY")
        ?: System.getenv("GOOGLE_MAPS_API_KEY")
        ?: ""

